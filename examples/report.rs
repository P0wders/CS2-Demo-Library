//! Writes a Markdown report for one or more demos: result, scoreboard, round
//! history, kill feed, the consistency checks the parser ran, and timings.
//!
//! cargo run --release --example report -- a.dem [b.dem ...] > report.md

use cs2_demo::entities::FieldPath;
use cs2_demo::stats::{MatchStats, PlayerStats};
use cs2_demo::{
    Context, Demo, Entity, EntityOp, GameEvent, ParseOptions, RoundEndReason, StatsCollector, Visitor,
};
use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;
use std::ops::ControlFlow;
use std::path::Path;
use std::time::{Duration, Instant};

type Res<T> = Result<T, Box<dyn std::error::Error>>;

fn main() -> Res<()> {
    let paths: Vec<String> = std::env::args().skip(1).collect();
    if paths.is_empty() {
        return Err("usage: report <demo.dem> [more.dem ...] > report.md".into());
    }
    let mut summary = String::new();
    let mut sections = String::new();
    for path in &paths {
        let r = analyze(Path::new(path))?;
        summary.push_str(&r.summary_row);
        sections.push_str(&r.section);
    }

    let mut out = String::new();
    writeln!(out, "# Demo report\n")?;
    writeln!(
        out,
        "Generated by `cargo run --release --example report` (cs2_demo {}).\n",
        env!("CARGO_PKG_VERSION")
    )?;
    writeln!(out, "| Demo | Map | Result | Rounds | Checks | Full parse |")?;
    writeln!(out, "|---|---|---|--:|---|--:|")?;
    out.push_str(&summary);
    out.push('\n');
    out.push_str(&sections);
    print!("{out}");
    Ok(())
}

/// Runs the built-in stats and counts what the parser delivered.
#[derive(Default)]
struct Collect {
    stats: StatsCollector,
    game_events: u64,
    entity_updates: u64,
    ticks: u64,
    match_over: bool,
    /// (deaths, assists) credited after the final scoreboard, per SteamID. The
    /// game's scoreboard may count these disconnect "suicides"; the stats don't.
    post_match: HashMap<u64, (i32, i32)>,
}

impl Visitor for Collect {
    fn on_start(&mut self, ctx: &Context) {
        self.stats.on_start(ctx);
    }

    fn on_game_event(&mut self, ctx: &Context, ev: &GameEvent) {
        self.game_events += 1;
        match &*ev.name {
            "cs_win_panel_match" => self.match_over = true,
            "player_death" if self.match_over => {
                for (field, is_death) in [("userid", true), ("assister", false)] {
                    if let Some(p) = ev.player_slot(field).and_then(|s| ctx.player_by_slot(s)) {
                        let e = self.post_match.entry(p.steam_id()).or_default();
                        if is_death {
                            e.0 += 1;
                        } else {
                            e.1 += 1;
                        }
                    }
                }
            }
            _ => {}
        }
        self.stats.on_game_event(ctx, ev);
    }

    fn on_entity(&mut self, ctx: &Context, e: &Entity, op: EntityOp, changed: &[FieldPath]) {
        if matches!(op, EntityOp::Created | EntityOp::Updated) {
            self.entity_updates += 1;
        }
        self.stats.on_entity(ctx, e, op, changed);
    }

    fn on_tick_end(&mut self, ctx: &Context) -> ControlFlow<()> {
        self.ticks += 1;
        self.stats.on_tick_end(ctx)
    }
}

/// Stops as soon as the first tick of game state has been decoded.
struct FirstTick;

impl Visitor for FirstTick {
    fn on_tick_end(&mut self, _: &Context) -> ControlFlow<()> {
        ControlFlow::Break(())
    }
}

struct Analysis {
    summary_row: String,
    section: String,
}

fn timed<T>(f: impl FnOnce() -> T) -> (T, Duration) {
    let start = Instant::now();
    let v = f();
    (v, start.elapsed())
}

fn analyze(path: &Path) -> Res<Analysis> {
    let file = path
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();
    let (demo, t_open) = timed(|| Demo::open(path));
    let demo = demo?;
    let mb = demo.bytes().len() as f64 / 1e6;
    let (ready, t_ready) = timed(|| demo.parse(ParseOptions::default(), &mut FirstTick));
    ready?;
    let (events, t_events) = timed(|| demo.parse(ParseOptions::events_only(), &mut ()));
    events?;
    let mut c = Collect::default();
    let (ctx, t_full) = timed(|| demo.parse(ParseOptions::default(), &mut c));
    let ctx = ctx?;
    let post_match = std::mem::take(&mut c.post_match);
    let stats = std::mem::take(&mut c.stats).into_stats(&ctx);
    let h = demo.header();

    // Teams, winner first.
    let mut teams: Vec<_> = stats.teams.iter().collect();
    teams.sort_by_key(|t| -t.score);
    let team_order: Vec<String> = teams.iter().map(|t| t.name.clone()).collect();
    let result = teams
        .iter()
        .map(|t| format!("{} {}", md(&t.name), t.score))
        .collect::<Vec<_>>()
        .join(" – ");

    let checks = run_checks(&ctx, &stats, &c, &post_match);
    let failed = checks.iter().filter(|(ok, _)| !ok).count();

    let title: Vec<String> = team_order.iter().map(|n| md(n)).collect();
    let mut s = String::new();
    writeln!(s, "---\n\n## {} · `{}`\n", title.join(" vs "), h.map_name)?;
    writeln!(s, "| | |\n|---|---|")?;
    writeln!(s, "| File | `{file}` ({mb:.0} MB) |")?;
    writeln!(s, "| Server | {} |", md(&h.server_name))?;
    writeln!(s, "| Game build | {} (patch {}) |", h.build_num, h.patch_version)?;
    if let (Some(ticks), Some(secs)) = (h.playback_ticks, h.playback_time) {
        writeln!(
            s,
            "| Recording | {} · {} ticks at {} tick/s |",
            clock(secs),
            thousands(ticks as u64),
            h.tick_rate()
        )?;
    }

    // Result.
    let overtime = stats.teams.iter().any(|t| t.score_overtime > 0);
    writeln!(s, "\n### Result\n")?;
    writeln!(
        s,
        "| Team | Score | 1st half | 2nd half |{}",
        if overtime { " Overtime |" } else { "" }
    )?;
    writeln!(s, "|---|--:|--:|--:|{}", if overtime { "--:|" } else { "" })?;
    for (i, t) in teams.iter().enumerate() {
        let (b, e) = if i == 0 && stats.winner().is_some() {
            ("**", "**")
        } else {
            ("", "")
        };
        write!(
            s,
            "| {b}{}{e} | {b}{}{e} | {} | {} |",
            md(&t.name),
            t.score,
            t.score_first_half,
            t.score_second_half
        )?;
        if overtime {
            write!(s, " {} |", t.score_overtime)?;
        }
        s.push('\n');
    }

    write_scoreboard(&mut s, &stats, &team_order)?;
    write_details(&mut s, &stats, &team_order)?;
    write_rounds(&mut s, &stats, &team_order)?;
    write_highlights(&mut s, &stats)?;
    write_kill_feed(&mut s, &stats)?;

    // Checks.
    writeln!(s, "\n### Checks\n")?;
    for (ok, text) in &checks {
        writeln!(s, "- {} {text}", if *ok { "✅" } else { "❌" })?;
    }

    // Timings.
    writeln!(s, "\n### Parse time\n")?;
    writeln!(s, "Single run each, file already in the OS cache.\n")?;
    writeln!(s, "| Step | Time | Speed |\n|---|--:|--:|")?;
    writeln!(
        s,
        "| `Demo::open` (map the file, read the header) | {} | |",
        dur(t_open)
    )?;
    writeln!(
        s,
        "| First tick ready (schema, string tables, baselines) | {} | |",
        dur(t_ready)
    )?;
    writeln!(
        s,
        "| Events only (`ParseOptions::events_only()`) | {} | {:.0} MB/s |",
        dur(t_events),
        mb / t_events.as_secs_f64()
    )?;
    writeln!(
        s,
        "| Full parse with stats (all entities) | {} | {:.0} MB/s |",
        dur(t_full),
        mb / t_full.as_secs_f64()
    )?;
    writeln!(
        s,
        "\nDecoded {} ticks, {} game events and {} entity updates.",
        thousands(c.ticks),
        thousands(c.game_events),
        thousands(c.entity_updates)
    )?;

    let checks_cell = if failed == 0 {
        format!("✅ {} passed", checks.len())
    } else {
        format!("❌ {failed} of {} failed", checks.len())
    };
    let summary_row = format!(
        "| `{file}` | {} | {result} | {} | {checks_cell} | {:.1} s |\n",
        h.map_name,
        stats.rounds.len(),
        t_full.as_secs_f64()
    );
    Ok(Analysis {
        summary_row,
        section: s,
    })
}

/// The same checks as the integration tests, phrased for people.
fn run_checks(
    ctx: &Context,
    stats: &MatchStats,
    c: &Collect,
    post_match: &HashMap<u64, (i32, i32)>,
) -> Vec<(bool, String)> {
    let mut checks = Vec::new();
    let d = ctx.entity_diagnostics();
    checks.push((
        d.size_mismatches == 0 && d.baseline_errors == 0 && d.verified_updates == c.entity_updates,
        format!(
            "**Entity decoding:** {} of {} entity updates matched the bit length the server recorded \
             ({} mismatches, {} baseline errors).",
            thousands(d.verified_updates),
            thousands(c.entity_updates),
            d.size_mismatches,
            d.baseline_errors
        ),
    ));

    let players: Vec<_> = ctx.active_players().collect();
    let identified = players
        .iter()
        .filter(|p| {
            !p.name().is_empty()
                && ctx
                    .player_info(p.slot())
                    .is_some_and(|i| i.steam_id == p.steam_id() && i.name == p.name())
        })
        .count();
    checks.push((
        players.len() == 10 && identified == 10,
        format!(
            "**Players:** {} players on the two teams, {identified} with a name and SteamID that \
             agree with the server's player table.",
            players.len()
        ),
    ));

    let total: i32 = stats.teams.iter().map(|t| t.score).sum();
    let numbered = stats
        .rounds
        .iter()
        .enumerate()
        .all(|(i, r)| r.number == stats.rounds[0].number + i as u32);
    let with_winner = stats.rounds.iter().filter(|r| r.winner.is_some()).count();
    let last = stats.rounds.last().map_or(0, |r| r.number);
    checks.push((
        numbered && with_winner == stats.rounds.len() && last as i32 == total,
        format!(
            "**Rounds:** {} rounds recorded, numbered {}–{last}, {with_winner} with a winner; the final \
             score adds up to {total}.",
            stats.rounds.len(),
            stats.rounds.first().map_or(0, |r| r.number),
        ),
    ));

    if stats.rounds.first().is_some_and(|r| r.number == 1) {
        let mut matching = 0;
        let mut notes = Vec::new();
        for p in &players {
            let Some(ours) = stats.player(p.steam_id()) else {
                continue;
            };
            let server = p.scoreboard();
            let (pd, pa) = post_match.get(&p.steam_id()).copied().unwrap_or_default();
            let ok =
                |ours: u32, server: i32, post: i32| ours as i32 == server || ours as i32 + post == server;
            if ok(ours.kills, server.kills, 0)
                && ok(ours.deaths, server.deaths, pd)
                && ok(ours.assists, server.assists, pa)
            {
                matching += 1;
                if ours.deaths as i32 != server.deaths || ours.assists as i32 != server.assists {
                    notes.push(md(&ours.name));
                }
            }
        }
        let mut text = format!(
            "**Scoreboard:** kills, deaths and assists equal the game's own scoreboard for \
             {matching} of {} players.",
            players.len()
        );
        if !notes.is_empty() {
            write!(
                text,
                " ({} also got a death or assist from a player disconnecting after the match, which \
                 the game counts and the stats ignore.)",
                notes.join(", ")
            )
            .unwrap();
        }
        checks.push((matching == players.len(), text));
    }
    checks
}

fn write_scoreboard(s: &mut String, stats: &MatchStats, team_order: &[String]) -> std::fmt::Result {
    writeln!(s, "\n### Scoreboard")?;
    for team in team_order {
        writeln!(s, "\n**{}**\n", md(team))?;
        writeln!(s, "| Player | K | D | A | +/− | ADR | HS % | KAST | Rating |")?;
        writeln!(s, "|---|--:|--:|--:|--:|--:|--:|--:|--:|")?;
        for p in stats.players.iter().filter(|p| &p.team_name == team) {
            writeln!(
                s,
                "| {} | {} | {} | {} | {:+} | {:.1} | {:.0} % | {:.0} % | {:.2} |",
                md(&p.name),
                p.kills,
                p.deaths,
                p.assists,
                p.kills as i32 - p.deaths as i32,
                p.adr(),
                p.hs_ratio() * 100.0,
                p.kast() * 100.0,
                p.rating()
            )?;
        }
    }
    let others: Vec<&PlayerStats> = stats
        .players
        .iter()
        .filter(|p| !team_order.contains(&p.team_name))
        .collect();
    if !others.is_empty() {
        let names: Vec<String> = others.iter().map(|p| md(&p.name)).collect();
        writeln!(
            s,
            "\nAlso played (not on a team at the end): {}",
            names.join(", ")
        )?;
    }
    Ok(())
}

fn write_details(s: &mut String, stats: &MatchStats, team_order: &[String]) -> std::fmt::Result {
    writeln!(s, "\n### Duels, utility and objectives\n")?;
    writeln!(
        s,
        "| Player | Opening K–D | Trade kills | Traded deaths | Multi-kill rounds | Flashes | \
         Enemies flashed | Flash assists | Utility dmg | Smokes | Molotovs | HE | Plants | Defuses |"
    )?;
    writeln!(s, "|---|:-:|--:|--:|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|")?;
    // Same order as the scoreboard: winner first, then anyone without a team.
    let rank = |p: &PlayerStats| {
        team_order
            .iter()
            .position(|t| *t == p.team_name)
            .unwrap_or(team_order.len())
    };
    let mut players: Vec<&PlayerStats> = stats.players.iter().collect();
    players.sort_by_key(|p| rank(p));
    for p in players {
        let multi: Vec<String> = (2..=5)
            .filter(|&n| p.multi_kills[n] > 0)
            .map(|n| format!("{}×{n}K", p.multi_kills[n]))
            .collect();
        writeln!(
            s,
            "| {} | {}–{} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            md(&p.name),
            p.opening_kills,
            p.opening_deaths,
            p.trade_kills,
            p.traded_deaths,
            if multi.is_empty() {
                "–".to_string()
            } else {
                multi.join(", ")
            },
            p.flashbangs_thrown,
            p.enemies_flashed,
            p.flash_assists,
            p.utility_damage,
            p.smokes_thrown,
            p.molotovs_thrown,
            p.he_thrown,
            p.bomb_plants,
            p.bomb_defuses
        )?;
    }
    Ok(())
}

fn how(reason: Option<RoundEndReason>, bomb_planted: bool) -> &'static str {
    match reason {
        Some(RoundEndReason::TargetBombed) => "Bomb exploded",
        Some(RoundEndReason::BombDefused) => "Bomb defused",
        Some(RoundEndReason::TargetSaved) => "Time ran out",
        Some(RoundEndReason::TWin | RoundEndReason::CtWin) if bomb_planted => "Elimination (bomb planted)",
        Some(RoundEndReason::TWin | RoundEndReason::CtWin) => "Elimination",
        Some(RoundEndReason::TerroristsSurrender | RoundEndReason::CtSurrender) => "Surrender",
        Some(_) => "Other",
        None => "?",
    }
}

fn write_rounds(s: &mut String, stats: &MatchStats, team_order: &[String]) -> std::fmt::Result {
    writeln!(s, "\n### Rounds\n")?;
    let [a, b] = [0, 1].map(|i| team_order.get(i).map_or(String::new(), |n| md(n)));
    writeln!(s, "| # | Winner | Side | How | {a} – {b} | Kills |")?;
    writeln!(s, "|--:|---|:-:|---|:-:|--:|")?;
    let mut wins: HashMap<&str, u32> = HashMap::new();
    for r in &stats.rounds {
        let winner = r.winner_name.as_deref().unwrap_or("?");
        *wins.entry(winner).or_default() += 1;
        let score = |i: usize| {
            team_order
                .get(i)
                .map_or(0, |n| wins.get(n.as_str()).copied().unwrap_or(0))
        };
        writeln!(
            s,
            "| {} | {} | {} | {} | {} – {} | {} |",
            r.number,
            md(winner),
            r.winner.map_or("?", |t| t.short_name()),
            how(r.reason, r.bomb_planted),
            score(0),
            score(1),
            r.kills
        )?;
    }
    if stats.rounds.first().is_some_and(|r| r.number > 1) {
        writeln!(
            s,
            "\nThe recording starts at round {}: the running score counts only rounds in this file.",
            stats.rounds[0].number
        )?;
    }
    Ok(())
}

fn write_highlights(s: &mut String, stats: &MatchStats) -> std::fmt::Result {
    writeln!(s, "\n### Highlights\n")?;
    let team_of: HashMap<u64, &str> = stats
        .players
        .iter()
        .map(|p| (p.steam_id, p.team_name.as_str()))
        .collect();

    if let Some(best) = stats
        .players
        .iter()
        .max_by(|a, b| a.rating().total_cmp(&b.rating()))
    {
        writeln!(
            s,
            "- **Best rating:** {} ({}): {:.2}, {}–{} K–D, {:.1} ADR",
            md(&best.name),
            md(&best.team_name),
            best.rating(),
            best.kills,
            best.deaths,
            best.adr()
        )?;
    }

    // Rounds where one player got 3+ kills.
    let mut per_round: BTreeMap<(u32, u64), Vec<&str>> = BTreeMap::new();
    let mut names: HashMap<u64, &str> = HashMap::new();
    for k in stats.kills.iter().filter(|k| !k.team_kill) {
        if let (Some(a), Some(name)) = (k.attacker, &k.attacker_name) {
            per_round.entry((k.round, a)).or_default().push(&k.weapon);
            names.insert(a, name);
        }
    }
    let big: Vec<String> = per_round
        .iter()
        .filter(|(_, w)| w.len() >= 3)
        .map(|((round, a), weapons)| {
            let label = if weapons.len() == 5 {
                "ACE".to_string()
            } else {
                format!("{}K", weapons.len())
            };
            format!("round {round}: {} {label} ({})", md(names[a]), weapons.join(", "))
        })
        .collect();
    if big.is_empty() {
        writeln!(
            s,
            "- **Multi-kills:** no round with 3 or more kills by one player"
        )?;
    } else {
        writeln!(s, "- **Multi-kills (3+):** {}", big.join("; "))?;
    }

    // Opening duels per team: the first kill of each round.
    let mut openings: BTreeMap<&str, u32> = BTreeMap::new();
    for r in &stats.rounds {
        if let Some(first) = stats
            .kills
            .iter()
            .find(|k| k.round == r.number && !k.team_kill && k.attacker.is_some())
            && let Some(team) = first.attacker.and_then(|a| team_of.get(&a))
        {
            *openings.entry(team).or_default() += 1;
        }
    }
    let openings: Vec<String> = openings.iter().map(|(t, n)| format!("{} {n}", md(t))).collect();
    writeln!(s, "- **Opening kills by team:** {}", openings.join(", "))?;

    let mut weapons: HashMap<&str, u32> = HashMap::new();
    for k in stats
        .kills
        .iter()
        .filter(|k| !k.team_kill && k.attacker.is_some())
    {
        *weapons.entry(&k.weapon).or_default() += 1;
    }
    let mut weapons: Vec<_> = weapons.into_iter().collect();
    weapons.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
    let top: Vec<String> = weapons.iter().take(8).map(|(w, n)| format!("{w} {n}")).collect();
    writeln!(s, "- **Kills by weapon:** {}", top.join(", "))?;

    let hs = stats.kills.iter().filter(|k| k.headshot && !k.team_kill).count();
    let wallbangs = stats.kills.iter().filter(|k| k.wallbang).count();
    let smoke = stats.kills.iter().filter(|k| k.through_smoke).count();
    let blind = stats.kills.iter().filter(|k| k.attacker_blind).count();
    writeln!(
        s,
        "- **Kills:** {} in total, {hs} headshots, {wallbangs} wallbangs, {smoke} through smoke, \
         {blind} by a blinded player",
        stats.kills.len()
    )?;
    Ok(())
}

fn write_kill_feed(s: &mut String, stats: &MatchStats) -> std::fmt::Result {
    let name_of: HashMap<u64, &str> = stats
        .players
        .iter()
        .map(|p| (p.steam_id, p.name.as_str()))
        .collect();
    writeln!(
        s,
        "\n<details>\n<summary><b>Kill feed</b> ({} kills)</summary>\n",
        stats.kills.len()
    )?;
    for r in &stats.rounds {
        writeln!(
            s,
            "**Round {}** · {} wins as {} · {}\n",
            r.number,
            md(r.winner_name.as_deref().unwrap_or("?")),
            r.winner.map_or("?", |t| t.short_name()),
            how(r.reason, r.bomb_planted)
        )?;
        for k in stats.kills.iter().filter(|k| k.round == r.number) {
            let mut tags = Vec::new();
            for (on, tag) in [
                (k.headshot, "headshot"),
                (k.wallbang, "wallbang"),
                (k.through_smoke, "through smoke"),
                (k.noscope, "no-scope"),
                (k.attacker_blind, "while blind"),
                (k.team_kill, "team kill"),
            ] {
                if on {
                    tags.push(tag);
                }
            }
            let mut line = match &k.attacker_name {
                Some(a) => format!("{} ⟶ {} with {}", md(a), md(&k.victim_name), k.weapon),
                None => format!("{} died ({})", md(&k.victim_name), k.weapon),
            };
            if !tags.is_empty() {
                write!(line, ", {}", tags.join(", "))?;
            }
            if let Some(name) = k.assister.and_then(|a| name_of.get(&a)) {
                let kind = if k.flash_assist { "flash assist" } else { "assist" };
                write!(line, " ({kind}: {})", md(name))?;
            }
            if k.traded {
                line.push_str(" · traded");
            }
            writeln!(s, "1. {line}")?;
        }
        s.push('\n');
    }
    writeln!(s, "</details>")?;
    Ok(())
}

/// Escapes text for Markdown tables and inline text (player names can contain anything).
fn md(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        if matches!(
            ch,
            '\\' | '|' | '*' | '_' | '`' | '<' | '>' | '[' | ']' | '~' | '#'
        ) {
            out.push('\\');
        }
        out.push(ch);
    }
    out
}

fn thousands(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, ch) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(ch);
    }
    out
}

fn clock(secs: f32) -> String {
    let s = secs.round() as u64;
    format!("{}:{:02}:{:02}", s / 3600, s / 60 % 60, s % 60)
}

fn dur(d: Duration) -> String {
    let s = d.as_secs_f64();
    if s < 0.001 {
        format!("{:.2} ms", s * 1e3)
    } else if s < 1.0 {
        format!("{:.0} ms", s * 1e3)
    } else {
        format!("{s:.2} s")
    }
}
