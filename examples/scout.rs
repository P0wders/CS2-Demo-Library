//! Scouting report on a team from many demos, in Markdown: maps, sides,
//! pistols, buys, bomb sites, setups, opening duels, lineups and players.
//!
//! cargo run --release --example scout -- "<team>" <demo or folder> [more ...] > scouting.md
//!
//! Folders are searched for `.dem` files, subfolders included. Demos are
//! parsed in parallel. Without a team name that matches, the report lists the
//! teams found.

use cs2_demo::scouting::{Frequency, MapProfile, Record, Scouting, TeamProfile};
use cs2_demo::stats::BuyType;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::time::Instant;

type Res<T> = Result<T, Box<dyn std::error::Error>>;

fn main() -> Res<()> {
    let mut args = std::env::args().skip(1);
    let team = args
        .next()
        .ok_or("usage: scout \"<team>\" <demo or folder> [more ...] > scouting.md")?;
    let mut demos = Vec::new();
    for a in args {
        collect(Path::new(&a), &mut demos);
    }
    if demos.is_empty() {
        return Err("no .dem files found".into());
    }
    let started = Instant::now();
    let mut scouting = Scouting::new();
    let mut failed = Vec::new();
    for (path, result) in demos.iter().zip(cs2_demo::match_stats_many(&demos)) {
        match result {
            Ok(stats) => scouting.add(stats),
            Err(e) => failed.push(format!("{}: {e}", path.display())),
        }
    }
    eprintln!(
        "parsed {} demos in {:.1} s",
        demos.len(),
        started.elapsed().as_secs_f64()
    );
    let Some(profile) = scouting.team(&team) else {
        let mut out = format!("No team named \"{team}\" in these demos. Teams found:\n\n");
        for t in scouting.teams() {
            writeln!(out, "- {t}")?;
        }
        print!("{out}");
        return Ok(());
    };
    print!("{}", report(&profile, &failed)?);
    Ok(())
}

fn collect(path: &Path, out: &mut Vec<PathBuf>) {
    if path.is_dir() {
        let Ok(rd) = std::fs::read_dir(path) else { return };
        let mut entries: Vec<PathBuf> = rd.filter_map(|e| e.ok().map(|e| e.path())).collect();
        entries.sort();
        for p in entries {
            collect(&p, out);
        }
    } else if path.extension().is_some_and(|e| e.eq_ignore_ascii_case("dem")) {
        out.push(path.to_path_buf());
    }
}

fn rec(r: Record) -> String {
    if r.played == 0 {
        "–".into()
    } else {
        format!("{}/{} ({:.0} %)", r.won, r.played, r.rate() * 100.0)
    }
}

fn freq(f: &[Frequency], n: usize) -> String {
    if f.is_empty() {
        return "–".into();
    }
    f.iter()
        .take(n)
        .map(|f| format!("{} ({})", md(&f.what), f.count))
        .collect::<Vec<_>>()
        .join(", ")
}

fn report(p: &TeamProfile, failed: &[String]) -> Res<String> {
    let mut s = String::new();
    writeln!(s, "# Scouting: {}\n", md(&p.name))?;
    writeln!(
        s,
        "{} matches, {} won. Generated by `cargo run --release --example scout` (cs2_demo {}).\n",
        p.matches,
        p.wins,
        env!("CARGO_PKG_VERSION")
    )?;
    writeln!(s, "## Maps\n")?;
    writeln!(
        s,
        "| Map | Matches | Rounds | T rounds | CT rounds | Pistols | Plants A / B |"
    )?;
    writeln!(s, "|---|--:|--:|--:|--:|--:|--:|")?;
    for m in &p.maps {
        writeln!(
            s,
            "| {} | {}/{} | {} | {} | {} | {} | {} / {} |",
            m.map,
            m.wins,
            m.matches,
            rec(m.rounds()),
            rec(m.t),
            rec(m.ct),
            rec(m.pistols),
            m.plants_a,
            m.plants_b
        )?;
    }
    for m in &p.maps {
        map_section(&mut s, m)?;
    }
    writeln!(s, "\n## Players\n")?;
    writeln!(
        s,
        "| Player | Maps | Rating 1.0 | Rating 2.0* | ADR | KAST | Opening K–D | Clutches | T rating | CT rating | Accuracy | Head hits | Usual T spots | Usual CT spots |"
    )?;
    writeln!(s, "|---|--:|--:|--:|--:|--:|:-:|--:|--:|--:|--:|--:|---|---|")?;
    for pl in &p.players {
        let st = &pl.stats;
        writeln!(
            s,
            "| {} | {} | {:.2} | {:.2} | {:.1} | {:.0} % | {}–{} | {}/{} | {:.2} | {:.2} | {:.0} % | {:.0} % | {} | {} |",
            md(&pl.name),
            pl.matches,
            st.rating(),
            st.rating2_approx(),
            st.adr(),
            st.kast() * 100.0,
            st.opening_kills,
            st.opening_deaths,
            st.clutches_won,
            st.clutches,
            st.t.rating(),
            st.ct.rating(),
            st.aim.accuracy() * 100.0,
            st.aim.head_hit_ratio() * 100.0,
            freq(&pl.t_places, 3),
            freq(&pl.ct_places, 3)
        )?;
    }
    writeln!(
        s,
        "\n\\* Rating 2.0 is a community approximation; HLTV has not published the formula."
    )?;
    if !failed.is_empty() {
        writeln!(s, "\n## Demos that could not be read\n")?;
        for f in failed {
            writeln!(s, "- {}", md(f))?;
        }
    }
    Ok(s)
}

fn map_section(s: &mut String, m: &MapProfile) -> Res<()> {
    writeln!(s, "\n## {}\n", m.map)?;
    writeln!(
        s,
        "- **Record:** {} of {} matches won; rounds {}; T {}; CT {}.",
        m.wins,
        m.matches,
        rec(m.rounds()),
        rec(m.t),
        rec(m.ct)
    )?;
    writeln!(
        s,
        "- **Pistol rounds:** {}. **Opening duels:** T {}, CT {}.",
        rec(m.pistols),
        rec(m.t_openings),
        rec(m.ct_openings)
    )?;
    let plants = m.plants_a + m.plants_b;
    if plants > 0 {
        writeln!(
            s,
            "- **Bomb plants (T):** A {} ({:.0} %), B {} ({:.0} %) in {} T rounds{}.",
            m.plants_a,
            100.0 * m.plants_a as f32 / plants as f32,
            m.plants_b,
            100.0 * m.plants_b as f32 / plants as f32,
            m.t.played,
            m.avg_plant_time
                .map_or(String::new(), |t| format!(", on average {t:.0} s into the round"))
        )?;
    }
    writeln!(s, "- **Grenades:** {:.1} per round.", m.grenades_per_round)?;
    writeln!(
        s,
        "\n| Buy | Own buy: rounds won | Against this buy: rounds won |"
    )?;
    writeln!(s, "|---|--:|--:|")?;
    for b in BuyType::ALL {
        let (own, against) = (m.buy(b), m.against_buy(b));
        if own.played + against.played > 0 {
            writeln!(s, "| {} | {} | {} |", b.label(), rec(own), rec(against))?;
        }
    }
    writeln!(
        s,
        "\n**CT setups** (where the players stood 20 s into the round):\n"
    )?;
    for f in m.ct_setups.iter().take(5) {
        writeln!(s, "- {} ×{}", md(&f.what), f.count)?;
    }
    writeln!(s, "\n**T positions** 20 s into the round:\n")?;
    for f in m.t_setups.iter().take(5) {
        writeln!(s, "- {} ×{}", md(&f.what), f.count)?;
    }
    writeln!(
        s,
        "\n**Opening kills from:** {}. **Opening deaths at:** {}.",
        freq(&m.opening_kill_places, 5),
        freq(&m.opening_death_places, 5)
    )?;
    if !m.lineups.is_empty() {
        writeln!(
            s,
            "\n| Repeated lineup | Side | Thrown | From | Aim (pitch, yaw) | Jump |"
        )?;
        writeln!(s, "|---|:-:|--:|---|---|:-:|")?;
        for l in m.lineups.iter().take(10) {
            writeln!(
                s,
                "| {} | {} | {} | {} ({:.0}, {:.0}, {:.0}) | {:.1}°, {:.1}° | {} |",
                l.kind.label(),
                l.side.short_name(),
                l.count(),
                md(l.throw_place.as_deref().unwrap_or("?")),
                l.throw_pos[0],
                l.throw_pos[1],
                l.throw_pos[2],
                l.throw_angles[0],
                l.throw_angles[1],
                if l.jump_throw { "yes" } else { "" }
            )?;
        }
    }
    Ok(())
}

/// Escapes text for Markdown tables.
fn md(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        if matches!(ch, '\\' | '|' | '*' | '_' | '`' | '<' | '>' | '[' | ']' | '#') {
            out.push('\\');
        }
        out.push(ch);
    }
    out
}
